import { lazy, Suspense } from "react";
import { motion, AnimatePresence } from "motion/react";
import { Bot, FlaskConical, GitCommitVertical, Radio, Sparkles, UserRound } from "lucide-react";
import type { Decision } from "../../api/types";
import { STATUS_LABEL, VERDICT_COLOR } from "../../lib/constants";
import { clockTime, ms, shortHash } from "../../lib/format";
import { useNames } from "../../lib/names";
import { explainDecision } from "../../store/actions";
import { selectDecision, setState, useCurrentDecision, useStore } from "../../store/store";
import { cx, Empty, Spinner, VerdictChip } from "../ui/ui";
import { ChallengeCard } from "./ChallengeCard";
import { ActionDetails, AuditRefs, Block, LatencyBlock, PolicyChecks, ProvenanceList, RiskBlock, TrustBlock } from "./Sections";

const TraceModal = lazy(() => import("./TraceModal"));

function Hero({ d }: { d: Decision }) {
  const color = VERDICT_COLOR[d.verdict];
  return (
    <div className="relative overflow-hidden border-b border-line px-4 pt-3 pb-3.5">
      <div className="pointer-events-none absolute inset-0" style={{ background: `radial-gradient(420px 120px at 0% 0%, ${color}1f, transparent 70%)` }} />
      <div className="relative flex items-center justify-between gap-3">
        <VerdictChip verdict={d.verdict} size="lg" />
        <div className="text-right">
          <div className="text-[12px] font-medium" style={{ color }}>
            {STATUS_LABEL[d.status]}
          </div>
          <div className="ig-mono text-[11px] text-muted">decided in {ms(d.latency_ms.decision_ms)}</div>
        </div>
      </div>
      <p className="relative mt-2.5 text-[12px] leading-relaxed text-fg">{d.explanation}</p>
      {d.simulated_adversary && (
        <div className="relative mt-2.5 flex items-start gap-2 rounded-[4px] border border-block/40 bg-block/[0.06] px-2.5 py-1.5 text-[11px] leading-snug text-fg-2">
          <FlaskConical size={13} className="mt-px shrink-0 text-block" />
          <span>
            <span className="font-semibold text-block">Simulated adversarial proposal</span> (deterministic test harness, no live LLM)
          </span>
        </div>
      )}
    </div>
  );
}

function ExplainArea({ d }: { d: Decision }) {
  const st = useStore((s) => s.explain[d.decision_id]);
  if (!st) return null;
  return (
    <div className="border-b border-line px-4 py-3">
      <div className="mb-1.5 flex items-center gap-2">
        <Sparkles size={13} className="text-ibm-2" />
        <span className="ig-label">Granite explanation</span>
      </div>
      {st.status === "loading" && (
        <div className="flex items-center gap-2 text-[11.5px] text-muted">
          <Spinner size={12} /> Asking the local Granite model to rephrase the verified findings…
        </div>
      )}
      {st.status === "ok" && (
        <>
          <p className="text-[12px] leading-relaxed text-fg">{st.text}</p>
          <p className="mt-1 text-[10px] leading-snug text-dim">{st.meta}</p>
        </>
      )}
      {st.status === "unavailable" && (
        <div className="rounded-[4px] border border-challenge/30 bg-challenge/[0.05] px-2.5 py-2 text-[11px] leading-snug text-fg-2">
          <span className="font-medium text-challenge">Granite explainer not configured on this gateway (HTTP 503).</span> Server says: “{st.message}”. Verdicts never depend on the
          language model; the policy explanation above is generated by the gateway itself.
        </div>
      )}
      {st.status === "error" && <div className="text-[11px] text-block">Explanation failed: {st.message}</div>}
    </div>
  );
}

export function Inspector() {
  const d = useCurrentDecision();
  const followLatest = useStore((s) => s.followLatest);
  const traceId = useStore((s) => s.traceDecisionId);
  const challenge = useStore((s) => (d ? s.sim?.challenges.find((c) => c.decision_id === d.decision_id) ?? null : null)) ?? d?.challenge ?? null;
  const names = useNames();
  const explaining = useStore((s) => (d ? s.explain[d.decision_id]?.status === "loading" : false));

  return (
    <div className="flex h-full flex-col">
      <div className="flex h-11 shrink-0 items-center justify-between gap-2 border-b border-line px-4">
        <div className="flex min-w-0 items-center gap-2">
          <span className="ig-label">Decision inspector</span>
          {d && <span className="ig-mono truncate text-[10.5px] text-dim">{d.decision_id}</span>}
        </div>
        <button
          type="button"
          onClick={() => selectDecision(null)}
          className={cx(
            "flex h-6 items-center gap-1.5 rounded-[3px] border px-1.5 text-[10px] font-medium tracking-[0.1em]",
            followLatest ? "border-allow/40 text-allow" : "border-line text-muted hover:text-fg",
          )}
          title={followLatest ? "Following the latest decision" : "Pinned to a decision; click to follow the latest"}
        >
          <Radio size={11} /> {followLatest ? "LATEST" : "PINNED"}
        </button>
      </div>

      {!d ? (
        <div className="p-4">
          <Empty>
            No decisions yet in this sandbox. Run a scenario on the left, or submit a proposal from Studio. Every agent action is evaluated by the gateway and the verdict appears here.
          </Empty>
          <div className="mt-4 flex flex-col gap-2 text-[11.5px] leading-relaxed text-muted">
            <div className="flex items-center gap-2">
              <VerdictChip verdict="ALLOW" size="xs" /> executed in the simulated tools
            </div>
            <div className="flex items-center gap-2">
              <VerdictChip verdict="CHALLENGE" size="xs" /> held for supervisor approval
            </div>
            <div className="flex items-center gap-2">
              <VerdictChip verdict="BLOCK" size="xs" /> prevented before execution
            </div>
          </div>
        </div>
      ) : (
        <>
          <div className="min-h-0 flex-1 overflow-y-auto">
            <AnimatePresence mode="wait" initial={false}>
              <motion.div key={d.decision_id} initial={{ opacity: 0, y: 4 }} animate={{ opacity: 1, y: 0 }} exit={{ opacity: 0 }} transition={{ duration: 0.18 }}>
                <Hero d={d} />
                {challenge && <ChallengeCard d={d} challenge={challenge} />}
                <ExplainArea d={d} />

                <Block title="Agent" right={<span className="ig-mono text-[10px] text-dim">{clockTime(d.timestamp)}</span>}>
                  <div className="flex items-start gap-2.5">
                    <div className="flex h-7 w-7 shrink-0 items-center justify-center rounded-[4px] border border-line bg-white/[0.02]">
                      <Bot size={14} className="text-fg-2" />
                    </div>
                    <div className="min-w-0">
                      <div className="text-[12.5px] font-medium text-fg">{names.agent(d.action.agent_id)}</div>
                      <div className="ig-mono text-[10.5px] text-muted">
                        {d.action.agent_id}
                        {names.agentInfo(d.action.agent_id) && <span> · role {names.agentInfo(d.action.agent_id)?.role}</span>}
                      </div>
                    </div>
                  </div>
                </Block>

                <Block title="Original human intent">
                  {d.intent ? (
                    <>
                      <blockquote className="border-l-2 border-allow/60 pl-2.5 text-[12.5px] leading-relaxed text-fg">“{d.intent.instruction}”</blockquote>
                      <div className="mt-2 flex flex-col gap-0.5 text-[11px]">
                        <span className="flex items-center gap-1.5 text-fg-2">
                          <UserRound size={12} className="shrink-0 text-muted" />
                          <span className="whitespace-nowrap">{names.operator(d.intent.operator_id)}</span>
                          <span className="truncate text-muted">· {names.role(d.intent.operator_role)}</span>
                        </span>
                        <span className="ig-mono pl-[18px] text-[10px] text-dim" title={`HMAC signature ${d.intent.signature}`}>
                          {d.intent.intent_id} v{d.intent.version} · signed {shortHash(d.intent.signature, 10)}
                        </span>
                      </div>
                    </>
                  ) : (
                    <div className="text-[11.5px] text-block">No registered intent matched {d.action.intent_id} v{d.action.intent_version}.</div>
                  )}
                </Block>

                <Block title="Requested action">
                  <ActionDetails d={d} names={names} />
                  <div className="mt-2.5">
                    <div className="ig-label-sm">Provenance</div>
                    <ProvenanceList d={d} names={names} />
                  </div>
                </Block>

                <TrustBlock d={d} names={names} />
                <RiskBlock d={d} />
                <PolicyChecks d={d} />
                <LatencyBlock d={d} />
                <AuditRefs d={d} />
              </motion.div>
            </AnimatePresence>
          </div>
          <div className="grid shrink-0 grid-cols-2 gap-2 border-t border-line bg-ink-2/80 p-3">
            <button type="button" className="ig-btn h-8 text-[11px] font-semibold tracking-[0.1em]" onClick={() => setState({ traceDecisionId: d.decision_id })}>
              <GitCommitVertical size={14} /> TRACE THIS DECISION
            </button>
            <button type="button" className="ig-btn h-8 text-[11.5px]" disabled={explaining} onClick={() => void explainDecision(d.decision_id)}>
              {explaining ? <Spinner size={12} /> : <Sparkles size={13} className="text-ibm-2" />} Explain with Granite
            </button>
          </div>
        </>
      )}
      {traceId && (
        <Suspense fallback={null}>
          <TraceModal decisionId={traceId} onClose={() => setState({ traceDecisionId: null })} />
        </Suspense>
      )}
    </div>
  );
}
