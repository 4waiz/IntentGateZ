"""Latency / throughput benchmark of the IntentGate Z gateway.

Two modes:
* in-process: calls Gateway.evaluate directly (policy + features + ML + audit + simulation),
  isolating decision cost from HTTP;
* http: drives POST /api/actions/evaluate on a running server at several concurrency levels,
  sampling host CPU and the server's memory.

Each run records hardware/software facts so numbers are never quoted without context.

    python ml/benchmark.py --mode inprocess --n 3000 --reps 3
    python ml/benchmark.py --mode http --url http://127.0.0.1:8000 --n 1500 --concurrency 1,4,8,16
"""

from __future__ import annotations

import argparse
import json
import os
import platform
import random
import statistics
import sys
import threading
import time
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "backend"))


def host_facts() -> dict:
    cpuinfo = Path("/proc/cpuinfo").read_text() if Path("/proc/cpuinfo").exists() else ""
    machine = None
    for line in cpuinfo.splitlines():
        if "machine =" in line:
            machine = line.split("machine =")[1].split()[0]
            break
    feats = next((ln.split(":", 1)[1].split() for ln in cpuinfo.splitlines() if ln.startswith("features")), [])
    return {
        "architecture": platform.machine(),
        "machine_type": machine,
        "nnpa_facility": "nnpa" in feats,
        "cpu_count": os.cpu_count(),
        "python": platform.python_version(),
        "system": f"{platform.system()} {platform.release()}",
    }


def pct(a: list[float]) -> dict:
    x = np.asarray(a, dtype=float)
    return {
        "n": int(x.size),
        "p50": round(float(np.percentile(x, 50)), 3),
        "p95": round(float(np.percentile(x, 95)), 3),
        "p99": round(float(np.percentile(x, 99)), 3) if x.size >= 200 else None,
        "mean": round(float(x.mean()), 3),
        "max": round(float(x.max()), 3),
    }


def proposals(gw, s) -> list:
    """A realistic mix of proposals generated by the real scenario planners."""
    from intentgate import scenarios
    from intentgate.agents import compromised_planner_dispatch, plan_dispatch, plan_purchase, plan_reroute

    out = []
    for sid in ("reroute", "supply", "injection", "drift"):
        res = scenarios.run(gw, s, sid)
        for d in res["decisions"]:
            out.append(d.action)
    intents = {i.intent_id: i for i in s.intents.all()}
    w = s.world
    for intent in intents.values():
        ops = {o.value for o in intent.authorized_operations}
        if "reroute_ambulance" in ops:
            out.append(plan_reroute(w, intent, "amb_03", "INC-2041"))
        if "dispatch_ambulance" in ops:
            out.append(plan_dispatch(w, intent, "amb_02", "INC-2044"))
            feed = s.scenario.get("injection_feed")
            if feed:
                out.append(compromised_planner_dispatch(w, intent, "amb_02", "INC-2044", feed))
        if "purchase_supplies" in ops:
            for q in (200, 900, 4000, 9000):
                out.append(plan_purchase(intent, "sup_vitalis", "sku_trauma_kit", q, "hosp_northgate", "forecast"))
    from intentgate.schemas import AgentActionIn

    return [AgentActionIn.model_validate({k: v for k, v in a.model_dump().items() if k in AgentActionIn.model_fields}) for a in out]


def run_inprocess(n: int, reps: int) -> dict:
    os.environ.setdefault("INTENTGATE_DB_PATH", ":memory:")
    from intentgate.audit import AuditLog
    from intentgate.config import settings
    from intentgate.gateway import Gateway
    from intentgate.injection import InjectionDetector
    from intentgate.metrics import Metrics
    from intentgate.risk_model import RiskModel
    from intentgate.sessions import SessionManager

    audit = AuditLog(":memory:")
    inj = InjectionDetector(settings.artifacts_dir)
    risk = RiskModel(settings.artifacts_dir)
    sm = SessionManager(settings.signing_key)
    gw = Gateway(settings, audit, risk, inj, Metrics(), sm)
    runs = []
    for r in range(reps):
        s = sm.create()
        props = proposals(gw, s)
        rng = random.Random(r)
        dec, inf, pol, e2e, verdicts = [], [], [], [], {}
        t0 = time.perf_counter()
        for i in range(n):
            if i % 200 == 0:
                s = sm.create()
                props = proposals(gw, s)
            d = gw.evaluate(s, rng.choice(props), origin="benchmark")
            dec.append(d.latency_ms["decision_ms"])
            inf.append(d.latency_ms["inference_ms"])
            pol.append(d.latency_ms["policy_ms"])
            e2e.append(d.latency_ms["end_to_end_ms"])
            verdicts[d.verdict.value] = verdicts.get(d.verdict.value, 0) + 1
        wall = time.perf_counter() - t0
        runs.append({"decision_ms": pct(dec), "inference_ms": pct(inf), "policy_ms": pct(pol), "end_to_end_ms": pct(e2e), "throughput_decisions_per_s": round(n / wall, 1), "verdicts": verdicts})
    return {
        "mode": "in-process gateway (single thread, includes SQLite audit writes and simulation execution)",
        "model_runtime": risk.runtime,
        "model_version": risk.version,
        "accelerator": risk.accelerator,
        "decisions_per_rep": n,
        "repetitions": reps,
        "runs": runs,
        "summary": {
            "decision_p50_ms_median_of_reps": round(statistics.median(r["decision_ms"]["p50"] for r in runs), 3),
            "decision_p95_ms_median_of_reps": round(statistics.median(r["decision_ms"]["p95"] for r in runs), 3),
            "throughput_median_of_reps": round(statistics.median(r["throughput_decisions_per_s"] for r in runs), 1),
        },
    }


class CpuSampler(threading.Thread):
    def __init__(self) -> None:
        super().__init__(daemon=True)
        self.samples: list[float] = []
        self.stop = threading.Event()

    @staticmethod
    def _read():
        with open("/proc/stat") as f:
            v = list(map(int, f.readline().split()[1:]))
        idle = v[3] + v[4]
        return sum(v), idle

    def run(self) -> None:
        if not Path("/proc/stat").exists():
            return
        t0, i0 = self._read()
        while not self.stop.wait(0.5):
            t1, i1 = self._read()
            if t1 > t0:
                self.samples.append(100.0 * (1 - (i1 - i0) / (t1 - t0)))
            t0, i0 = t1, i1


def run_http(url: str, n: int, levels: list[int], operator_token: str = "") -> dict:
    import httpx

    OPH = {"X-IG-Operator": operator_token} if operator_token else {}
    client = httpx.Client(base_url=url, timeout=30, headers=OPH)
    sess = client.post("/api/session").json()
    H = {"X-IG-Session": sess["session_id"]}
    for sid in ("reroute", "supply", "injection", "drift"):
        client.post(f"/api/scenarios/{sid}/run", headers=H)
    decs = client.get("/api/decisions?limit=20", headers=H).json()
    bodies = []
    for d in decs:
        full = client.get(f"/api/decisions/{d['decision_id']}", headers=H).json()
        a = full["action"]
        bodies.append({k: a[k] for k in ("agent_id", "intent_id", "intent_version", "action_type", "tool", "target", "parameters", "provenance", "rationale", "required_permissions")})
    results = []
    for c in levels:
        lat: list[float] = []
        errors = 0
        lock = threading.Lock()
        per = max(1, n // c)

        def worker(k: int) -> None:
            nonlocal errors
            cl = httpx.Client(base_url=url, timeout=30, headers=OPH)
            s2 = cl.post("/api/session").json()
            h2 = {"X-IG-Session": s2["session_id"]}
            # Re-register intents in this worker's sandbox by running scenarios once.
            for sid in ("reroute", "supply", "injection", "drift"):
                cl.post(f"/api/scenarios/{sid}/run", headers=h2)
            mine = []
            for d in cl.get("/api/decisions?limit=20", headers=h2).json():
                full = cl.get(f"/api/decisions/{d['decision_id']}", headers=h2).json()
                a = full["action"]
                mine.append({kk: a[kk] for kk in ("agent_id", "intent_id", "intent_version", "action_type", "tool", "target", "parameters", "provenance", "rationale", "required_permissions")})
            rng = random.Random(k)
            for _ in range(per):
                t0 = time.perf_counter()
                r = cl.post("/api/actions/evaluate", headers=h2, json=rng.choice(mine))
                dt = (time.perf_counter() - t0) * 1000
                with lock:
                    if r.status_code == 200:
                        lat.append(dt)
                    else:
                        errors += 1

        cpu = CpuSampler()
        cpu.start()
        t0 = time.perf_counter()
        th = [threading.Thread(target=worker, args=(k,)) for k in range(c)]
        for t in th:
            t.start()
        for t in th:
            t.join()
        wall = time.perf_counter() - t0
        cpu.stop.set()
        m = client.get("/api/metrics").json()
        results.append({"concurrency": c, "requests": len(lat) + errors, "errors": errors, "latency_ms": pct(lat) if lat else None, "throughput_rps": round(len(lat) / wall, 1), "host_cpu_pct_mean": round(statistics.mean(cpu.samples), 1) if cpu.samples else None, "server_rss_mb": m.get("memory", {}).get("process_rss_mb")})
        print(results[-1])
    info = client.get("/api/health").json()
    return {"mode": "HTTP POST /api/actions/evaluate (client on the same VM; includes setup per worker excluded from latency)", "server": info, "levels": results}


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--mode", choices=["inprocess", "http"], default="inprocess")
    ap.add_argument("--n", type=int, default=2000)
    ap.add_argument("--reps", type=int, default=3)
    ap.add_argument("--url", default="http://127.0.0.1:8000")
    ap.add_argument("--concurrency", default="1,4,8,16")
    ap.add_argument("--out", default=str(ROOT / "ml" / "results"))
    ap.add_argument("--operator-token", default=os.environ.get("IG_OPERATOR_TOKEN", ""), help="exempts the load generator from the public rate limit")
    args = ap.parse_args()
    started = time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime())
    if args.mode == "inprocess":
        res = run_inprocess(args.n, args.reps)
        name = "benchmark_inprocess"
    else:
        res = run_http(args.url, args.n, [int(x) for x in args.concurrency.split(",")], args.operator_token)
        name = "benchmark_http"
    res.update({"host": host_facts(), "started_at": started})
    Path(args.out).mkdir(parents=True, exist_ok=True)
    (Path(args.out) / f"{name}.json").write_text(json.dumps(res, indent=2))
    print(json.dumps(res.get("summary", res.get("levels")), indent=2))


if __name__ == "__main__":
    main()
